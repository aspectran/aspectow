package com.aspectran.aspectow.console.common.db.model;

import java.io.Serial;
import java.io.Serializable;
import java.time.LocalDateTime;

/**
 * Entity representing an in-app notification history record.
 *
 * <p>Created: 2026-11-17</p>
 */
public class NotificationHistory implements Serializable {

    @Serial
    private static final long serialVersionUID = 1L;

    private Long notificationId;
    private Long userId;
    private String category;
    private String severity;
    private String title;
    private String message;
    private String targetUrl;
    private String readYn = "N";
    private LocalDateTime createdAt;

    public Long getNotificationId() {
        return notificationId;
    }

    public void setNotificationId(Long notificationId) {
        this.notificationId = notificationId;
    }

    public Long getUserId() {
        return userId;
    }

    public void setUserId(Long userId) {
        this.userId = userId;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public String getSeverity() {
        return severity;
    }

    public void setSeverity(String severity) {
        this.severity = severity;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public String getTargetUrl() {
        return targetUrl;
    }

    public void setTargetUrl(String targetUrl) {
        this.targetUrl = targetUrl;
    }

    public String getReadYn() {
        return readYn;
    }

    public void setReadYn(String readYn) {
        this.readYn = readYn;
    }

    public boolean isRead() {
        return "Y".equalsIgnoreCase(readYn);
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    @Override
    public String toString() {
        return "NotificationHistory{" +
                "notificationId=" + notificationId +
                ", userId=" + userId +
                ", category='" + category + '\'' +
                ", severity='" + severity + '\'' +
                ", title='" + title + '\'' +
                ", readYn='" + readYn + '\'' +
                ", createdAt=" + createdAt +
                '}';
    }

}
